// Compile the mobile's platform-independent logic for extension pages.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('../mobile/node_modules/typescript');
const modules = ['TitleText', 'ProductComparison', 'ProductSearch', 'SearchHistory', 'StoreOffers', 'MatchingEngine', 'ProductDetails'];
let output = '// Generated by scripts/build-extension-core.cjs; edit mobile/src/core sources.\n(function(root) {\nconst modules = {};\n';
for (const name of modules) {
  const source = fs.readFileSync(path.join(__dirname, '../mobile/src/core', name + '.ts'), 'utf8');
  const js = ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020}}).outputText;
  output += `modules['./${name}'] = (() => { const exports = {}; const require = name => modules[name];\n${js}\nreturn exports; })();\n`;
}
output += 'root.LowPCore = Object.assign({}, ...Object.values(modules));\n})(globalThis);\n';
const target = path.join(__dirname, '../src/shared/mobile-core.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw Error('Run npm run build:extension to update shared logic');
} else {
  fs.mkdirSync(path.dirname(target), {recursive: true});
  fs.writeFileSync(target, output);
}
